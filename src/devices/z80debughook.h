#pragma once

#include "types.h"

// ---------------------------------------------------------------------------
//	Z80C の実行ループに割り込むためのフック。
//	Z80C::SetDebugHook で登録する。フック未登録時 (debughook == 0) は
//	既存の実行ループと完全に同じコードパスを通る。
//
class IZ80DebugHook
{
public:
	virtual ~IZ80DebugHook() {}

	// 1命令実行の直前に呼ばれる。true を返すと、その命令を実行せずに
	// 実行ループを打ち切る (Z80C::Stop(0) 相当)
	virtual bool CheckExecBreak(int cpuid, uint pc) = 0;
};
